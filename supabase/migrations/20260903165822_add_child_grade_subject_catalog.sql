create or replace function private.update_child_profile_details(
  p_child_profile_id uuid,
  p_child_name text,
  p_grade_level smallint
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_grade_level is null or p_grade_level not between 1 and 12 then
    raise exception 'Grade level must be between 1 and 12';
  end if;

  if not private.update_child_profile(p_child_profile_id, p_child_name) then
    return false;
  end if;

  update public.profiles
  set grade_level = p_grade_level, updated_at = now()
  where id = p_child_profile_id;

  return found;
end;
$$;

