-- Store the child's current grade and serve curriculum-aware subject suggestions
-- from database configuration. UI components must not embed a subject list.

alter table public.profiles
  add column if not exists grade_level smallint;

alter table public.profiles
  drop constraint if exists profiles_grade_level_check;

alter table public.profiles
  add constraint profiles_grade_level_check
  check (grade_level is null or grade_level between 1 and 12);

comment on column public.profiles.grade_level is
  'Current Vietnamese general-education grade (1-12); education stage is derived automatically.';

create table if not exists private.curriculum_subject_catalog (
  id bigint generated by default as identity primary key,
  subject_name text not null check (length(trim(subject_name)) > 0),
  education_stage text not null check (education_stage in ('primary', 'lower_secondary', 'upper_secondary')),
  min_grade smallint not null check (min_grade between 1 and 12),
  max_grade smallint not null check (max_grade between 1 and 12 and max_grade >= min_grade),
  curriculum_group text not null check (curriculum_group in ('required', 'elective', 'optional')),
  sort_order integer not null default 0,
  source_document text not null,
  source_url text not null,
  effective_from date not null,
  updated_at timestamptz not null default now(),
  unique (subject_name, education_stage, min_grade, max_grade, curriculum_group)
);

alter table private.curriculum_subject_catalog enable row level security;
revoke all on table private.curriculum_subject_catalog from public, anon, authenticated;
revoke all on sequence private.curriculum_subject_catalog_id_seq from public, anon, authenticated;

drop policy if exists "deny direct curriculum catalog access" on private.curriculum_subject_catalog;
create policy "deny direct curriculum catalog access"
  on private.curriculum_subject_catalog
  for all
  to public
  using (false)
  with check (false);

comment on table private.curriculum_subject_catalog is
  'Vietnamese general-education subject catalog sourced from the consolidated 2018 curriculum and Circular 13/2022.';

