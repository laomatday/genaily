drop function if exists public.get_account_children();
create function public.get_account_children()
returns table (
  account_space_id uuid,
  parent_profile_id uuid,
  child_profile_id uuid,
  child_name text,
  child_avatar_url text,
  child_grade_level smallint,
  child_joined_at timestamptz
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    family.id,
    (select auth.uid()),
    child_profile.id,
    child_profile.full_name,
    child_profile.avatar_url,
    child_profile.grade_level,
    child_member.joined_at
  from public.families family
  join public.family_members child_member
    on child_member.family_id = family.id
   and child_member.role = 'child'
   and child_member.status = 'active'
  join public.profiles child_profile
    on child_profile.id = child_member.profile_id
  where family.created_by = (select auth.uid())
  order by child_member.joined_at, child_profile.id;
$$;

revoke all on function public.get_account_children() from public, anon;
grant execute on function public.get_account_children() to authenticated;

create or replace function private.get_subject_suggestions(p_child_profile_id uuid)
returns table (
  subject_name text,
  education_stage text,
  curriculum_group text,
  sort_order integer
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_grade_level smallint;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required';
  end if;

  select child_profile.grade_level
  into v_grade_level
  from public.families family
  join public.family_members child_member
    on child_member.family_id = family.id
   and child_member.profile_id = p_child_profile_id
   and child_member.role = 'child'
   and child_member.status = 'active'
  join public.profiles child_profile
    on child_profile.id = child_member.profile_id
  where family.created_by = (select auth.uid())
    and private.can_access_child(family.id, p_child_profile_id)
  limit 1;

  if not found then
    raise exception 'Child profile is not owned by this account';
  end if;

  if v_grade_level is null then
    return;
  end if;

  return query
  select
    catalog.subject_name,
    catalog.education_stage,
    catalog.curriculum_group,
    catalog.sort_order
  from private.curriculum_subject_catalog catalog
  where v_grade_level between catalog.min_grade and catalog.max_grade
  order by
    case catalog.curriculum_group
      when 'required' then 1
      when 'elective' then 2
      else 3
    end,
    catalog.sort_order,
    catalog.subject_name;
end;
$$;

