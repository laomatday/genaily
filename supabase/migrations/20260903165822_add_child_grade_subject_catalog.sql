create or replace function private.add_child_profile_with_grade(
  p_child_name text,
  p_grade_level smallint
)
returns table (
  account_space_id uuid,
  parent_profile_id uuid,
  child_profile_id uuid,
  child_name text,
  child_grade_level smallint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_created record;
begin
  if p_grade_level is null or p_grade_level not between 1 and 12 then
    raise exception 'Grade level must be between 1 and 12';
  end if;

  select * into strict v_created
  from private.add_child_profile(p_child_name);

  update public.profiles
  set grade_level = p_grade_level, updated_at = now()
  where id = v_created.child_profile_id;

  return query select
    v_created.account_space_id,
    v_created.parent_profile_id,
    v_created.child_profile_id,
    v_created.child_name,
    p_grade_level;
end;
$$;

revoke all on function private.add_child_profile_with_grade(text, smallint)
  from public, anon, authenticated, service_role;
grant execute on function private.add_child_profile_with_grade(text, smallint) to authenticated;

